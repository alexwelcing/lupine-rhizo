import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["src/workspace/client/main.tsx"],
  outfile: "workspace-app.js", bundle: true, write: false, minify: true,
  format: "esm", platform: "browser", target: ["safari16", "chrome110"],
  define: { "process.env.NODE_ENV": '"production"' },
});
const js = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text;
const css = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text;
if (!js || !css) throw new Error("Workspace JavaScript or stylesheet was not produced.");
const directory = new URL("../src/workspace/generated/", import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(new URL("client.ts", directory),
  `// Generated by npm run build:workspace. Do not edit.\nexport const workspaceJavaScript = ${JSON.stringify(js)};\nexport const workspaceStyles = ${JSON.stringify(css)};\n`);
console.log(`Workspace bundled locally: ${Math.round(js.length / 1024)} KiB JS, ${Math.round(css.length / 1024)} KiB CSS.`);
